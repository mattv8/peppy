use peppy_desktop_api::{
    ConversationFolderDto, ConversationFolderReasonDto, ConversationView, HistoryPage,
    SenderUnblockStatusDto,
    group::{GroupNoticeKindView, GroupNoticeView, GroupState, GroupView},
    reactions::ReactionSupportDto,
};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn contracts() -> String {
    let declarations = [
        ConversationFolderDto::decl(),
        ConversationFolderReasonDto::decl(),
        SenderUnblockStatusDto::decl(),
        ReactionSupportDto::decl(),
        GroupState::decl(),
        GroupNoticeKindView::decl(),
        GroupNoticeView::decl(),
        GroupView::decl(),
        ConversationView::decl(),
        HistoryPage::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!(
        "// Generated by ts-rs; do not edit.\n\nimport type {{ MessageView }} from \"./message\";\n\n{declarations}\n"
    )
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/generated/src/conversation.ts");
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            contracts(),
            "generated contracts are stale; rerun generate-conversation-contracts"
        );
    } else {
        fs::write(path, contracts()).expect("write generated conversation contracts");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn conversation_typescript_is_current() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../packages/generated/src/conversation.ts");
        assert_eq!(fs::read_to_string(path).unwrap(), contracts());
    }
}
