use peppy_desktop_api::{LaunchPhase, LaunchProgress, LaunchStep, LaunchUpdate};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn contracts() -> String {
    let declarations = [
        LaunchPhase::decl(),
        LaunchStep::decl(),
        LaunchUpdate::decl(),
        LaunchProgress::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!("// Generated by ts-rs; do not edit.\n\n{declarations}\n")
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/generated/src/launch-progress.ts");
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            contracts(),
            "generated contracts are stale; rerun generate-launch-progress-contracts"
        );
    } else {
        fs::write(path, contracts()).expect("write generated launch progress contracts");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn launch_progress_typescript_matches_frozen_shape() {
        assert_eq!(LaunchPhase::decl(), "type LaunchPhase = \"starting\" | \"unlocking\" | \"opening\" | \"updating\" | \"loading\" | \"ready\";");
        assert_eq!(
            LaunchStep::decl(),
            "type LaunchStep = { phase: LaunchPhase, durationMs: number, };"
        );
        assert_eq!(
            LaunchUpdate::decl(),
            "type LaunchUpdate = { completed: number, total: number, };"
        );
        assert_eq!(LaunchProgress::decl(), "type LaunchProgress = { phase: LaunchPhase, elapsedMs: number, steps: Array<LaunchStep>, update?: LaunchUpdate, };");
    }

    #[test]
    fn launch_progress_typescript_is_current() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../packages/generated/src/launch-progress.ts");
        assert_eq!(fs::read_to_string(path).unwrap(), contracts());
    }
}
