use peppy_desktop_api::{
    AttachmentStateDto, AttachmentTransfer, AttachmentView, DraftAttachmentState, GroupHint,
    MediaHold, MediaMetadataView, MediaPreviewUnavailable, MessageReactionView, MessageSender,
    MessageStatus, MessageTransport, MessageView, OwnReactionRefusal, OwnReactionRequestState,
    OwnReactionRequestView, RcsAttachmentState, RcsSendStatus, ReactionActorView, ReactionRouteDto,
    SendCancellationStateDto, SendCancellationView, SendRecoveryKind, SendRecoveryView,
    SentAgainView,
};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn contracts() -> String {
    let declarations = [
        MessageSender::decl(),
        MessageStatus::decl(),
        GroupHint::decl(),
        MessageTransport::decl(),
        SendCancellationStateDto::decl(),
        AttachmentStateDto::decl(),
        AttachmentTransfer::decl(),
        MediaHold::decl(),
        DraftAttachmentState::decl(),
        RcsAttachmentState::decl(),
        RcsSendStatus::decl(),
        MediaPreviewUnavailable::decl(),
        ReactionRouteDto::decl(),
        OwnReactionRequestState::decl(),
        OwnReactionRefusal::decl(),
        SendRecoveryKind::decl(),
        MediaMetadataView::decl(),
        AttachmentView::decl(),
        SendCancellationView::decl(),
        ReactionActorView::decl(),
        MessageReactionView::decl(),
        OwnReactionRequestView::decl(),
        SentAgainView::decl(),
        SendRecoveryView::decl(),
        MessageView::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!("// Generated by ts-rs; do not edit.\n\n{declarations}\n")
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/generated/src/message.ts");
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            contracts(),
            "generated contracts are stale; rerun generate-message-contracts"
        );
    } else {
        fs::write(path, contracts()).expect("write generated message contracts");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn message_typescript_is_current() {
        let path =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/generated/src/message.ts");
        assert_eq!(fs::read_to_string(path).unwrap(), contracts());
    }
}
