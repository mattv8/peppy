use peppy_desktop_api::{
    RcsConversationEligibility, RcsEligibilityState, RcsGatewayState, RcsGatewayStatus,
    RcsStatusSnapshot,
};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn contracts() -> String {
    let declarations = [
        RcsGatewayState::decl(),
        RcsEligibilityState::decl(),
        RcsGatewayStatus::decl(),
        RcsConversationEligibility::decl(),
        RcsStatusSnapshot::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!("// Generated by ts-rs; do not edit.\n\n{declarations}\n")
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("packages/generated/src/rcs-status.ts");
    let expected = contracts();
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            expected,
            "generated contracts are stale; rerun generate-rcs-status-contracts"
        );
    } else {
        fs::write(path, expected).expect("write generated RCS status contracts");
    }
}
