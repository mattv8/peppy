use peppy_desktop_api::{
    AdvanceSearchIndexInputView, LocalSearchHitView, LocalSearchPageView, LocalSearchRequestView,
    MessageWindowRequestView, MessageWindowView, SearchHasMoreView, SearchIndexProgressView,
    SearchIndexStateView, SearchKind,
};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn contracts() -> String {
    let declarations = [
        SearchKind::decl(),
        LocalSearchRequestView::decl(),
        AdvanceSearchIndexInputView::decl(),
        LocalSearchHitView::decl(),
        SearchHasMoreView::decl(),
        LocalSearchPageView::decl(),
        SearchIndexStateView::decl(),
        SearchIndexProgressView::decl(),
        MessageWindowRequestView::decl(),
        MessageWindowView::<()>::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!("// Generated by ts-rs; do not edit.\n\n{declarations}\n")
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("packages/generated/src/local-search.ts");
    let expected = contracts();
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            expected,
            "generated contracts are stale; rerun generate-search-contracts"
        );
    } else {
        fs::write(path, expected).expect("write generated search contracts");
    }
}
