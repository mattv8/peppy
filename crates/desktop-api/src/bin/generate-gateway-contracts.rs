use peppy_desktop_api::{GatewayAvailability, GatewayPresence, GatewayPresenceState, GatewayView};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn contracts() -> String {
    let declarations = [
        GatewayAvailability::decl(),
        GatewayPresenceState::decl(),
        GatewayPresence::decl(),
        GatewayView::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!("// Generated by ts-rs; do not edit.\n\n{declarations}\n")
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/generated/src/gateway.ts");
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            contracts(),
            "generated contracts are stale; rerun generate-gateway-contracts"
        );
    } else {
        fs::write(path, contracts()).expect("write generated gateway contracts");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gateway_typescript_is_current() {
        let path =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/generated/src/gateway.ts");
        assert_eq!(fs::read_to_string(path).unwrap(), contracts());
    }
}
