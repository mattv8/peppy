use peppy_desktop_api::{NotificationDismissalBlock, NotificationDismissalBlockReason};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn contracts() -> String {
    let declarations = [
        NotificationDismissalBlockReason::decl(),
        NotificationDismissalBlock::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!("// Generated by ts-rs; do not edit.\n\n{declarations}\n")
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/generated/src/notification-dismissal.ts");
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            contracts(),
            "generated contracts are stale; rerun generate-notification-dismissal-contracts"
        );
    } else {
        fs::write(path, contracts()).expect("write generated notification dismissal contracts");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn notification_dismissal_typescript_is_current() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../packages/generated/src/notification-dismissal.ts");
        assert_eq!(fs::read_to_string(path).unwrap(), contracts());
    }
}
