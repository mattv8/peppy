use peppy_desktop_api::account_access::{
    AccountAccessResult, AccountNoticeDto, AccountNoticeKindDto, AccountNoticeSeverityDto,
};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn contracts() -> String {
    let declarations = [
        AccountNoticeKindDto::decl(),
        AccountNoticeSeverityDto::decl(),
        AccountNoticeDto::decl(),
        AccountAccessResult::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!("// Generated by ts-rs; do not edit.\n\n{declarations}\n")
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("packages/generated/src/account-access.ts");
    let expected = contracts();
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            expected,
            "generated contracts are stale; rerun generate-account-access-contracts"
        );
    } else {
        fs::write(path, expected).expect("write generated account access contracts");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_result_is_a_discriminated_union_with_camel_case_notice() {
        let declarations = contracts();
        assert!(declarations.contains("deadline: number | null"));
        assert!(declarations.contains("manageUrl: string | null"));
        assert!(declarations.contains("snoozeKey: string"));
        assert!(declarations.contains("\"kind\": \"temporarily_unavailable\""));
    }
}
