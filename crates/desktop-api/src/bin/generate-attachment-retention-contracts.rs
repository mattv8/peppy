fn contracts() -> String {
    let declarations = [
        AttachmentUseKindDto::decl(),
        AttachmentUseOperationKindDto::decl(),
        AttachmentUseStateDto::decl(),
        PendingAttachmentUseOperationDto::decl(),
        AttachmentUseResponseDto::decl(),
        AttachmentRetentionProtocolHeaderDto::decl(),
        AttachmentRetentionRequestDto::decl(),
        AttachmentRetentionProtocolConfigurationInput::decl(),
        AttachmentRetentionCapabilityInput::decl(),
        AttachmentRetentionAttachmentInput::decl(),
        AttachmentRetentionBeginInput::decl(),
        AttachmentRetentionPrepareInput::decl(),
        AttachmentRetentionResponseBodyInput::decl(),
        AttachmentRetentionNoticeRequestInput::decl(),
        AttachmentRetentionReleaseInput::decl(),
        AttachmentRetentionOperationsDto::decl(),
        AttachmentRetentionProtocolStatusDto::decl(),
        AttachmentRetentionReadyDto::decl(),
        AttachmentRetentionPreparationPendingDto::decl(),
        AttachmentRetentionClassDto::decl(),
        AttachmentUploadRetentionDto::decl(),
        RemoteAttachmentStateDto::decl(),
        AttachmentRetentionStateDto::decl(),
        RetentionNoticeStateDto::decl(),
        StorageCleanupStateDto::decl(),
        StorageCleanupUnavailableReasonDto::decl(),
        RetentionNoticeDto::decl(),
        AttachmentStorageStatusDto::decl(),
        AttachmentRetentionStatusResult::decl(),
        AttachmentRetentionNoticeAcknowledgementInput::decl(),
        AttachmentRetentionNoticeAcknowledgementResult::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!(
        "// Generated by ts-rs; do not edit.\n\nexport const SUPPORTED_ATTACHMENT_RETENTION_NOTICE_POLICY_VERSION = \"{CLIENT_SUPPORTED_ATTACHMENT_RETENTION_NOTICE_POLICY_VERSION}\" as const;\nexport const MAX_ATTACHMENT_RETENTION_RESPONSE_JSON_BYTES = {MAX_ATTACHMENT_RETENTION_RESPONSE_JSON} as const;\nexport const ATTACHMENT_RETENTION_RESPONSE_READ_LIMIT_BYTES = {} as const;\nexport const ATTACHMENT_RETENTION_PROTOCOL_HEADER_NAME = \"{ATTACHMENT_RETENTION_PROTOCOL_HEADER}\" as const;\nexport const ATTACHMENT_RETENTION_PROTOCOL_HEADER_VALUE = \"{ATTACHMENT_RETENTION_PROTOCOL_VERSION}\" as const;\nexport const MAX_PREPARED_ATTACHMENT_RETENTION_OPERATIONS = {} as const;\n\n{declarations}\n",
        MAX_ATTACHMENT_RETENTION_RESPONSE_JSON + 1,
        peppy_client_core::MAX_PREPARED_ATTACHMENT_RETENTION_OPERATIONS
    )
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("packages/generated/src/attachment-retention.ts");
    let expected = contracts();
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            expected,
            "generated contracts are stale; rerun generate-attachment-retention-contracts"
        );
    } else {
        fs::write(path, expected).expect("write generated attachment retention contracts");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_status_numbers_match_json_transport() {
        let declarations = contracts();
        assert!(declarations.contains("usedBytes: number"));
        assert!(declarations.contains("presentedAtSeconds: number | null"));
        assert!(
            declarations
                .contains("ATTACHMENT_RETENTION_RESPONSE_READ_LIMIT_BYTES = 16385 as const")
        );
        assert!(declarations.contains(
            "ATTACHMENT_RETENTION_PROTOCOL_HEADER_NAME = \"Peppy-Attachment-Retention-Protocol\" as const"
        ));
        assert!(
            declarations.contains("ATTACHMENT_RETENTION_PROTOCOL_HEADER_VALUE = \"1\" as const")
        );
    }
}
