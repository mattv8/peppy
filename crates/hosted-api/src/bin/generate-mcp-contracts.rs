use peppy_hosted_api::mcp::{
    MCP_COMPLETE_REQUEST_TIMEOUT_MS, McpAuthorizationDecision, McpAuthorizationView,
    McpDeviceState, McpDeviceStatus, McpDeviceView, McpGrantView, McpScope, WebhookCreated,
    WebhookDeliveryState, WebhookEvent, WebhookFilterEntry, WebhookFilterMode, WebhookInput,
    WebhookList, WebhookSecret, WebhookTestResult, WebhookView,
};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn exported_declaration<T: TS>() -> String {
    let declaration = T::decl();
    let declaration = declaration
        .strip_prefix("type ")
        .expect("ts-rs MCP declaration must begin with `type `");
    format!("export type {declaration}")
}

fn contracts() -> String {
    let declarations = [
        exported_declaration::<McpDeviceState>(),
        exported_declaration::<McpScope>(),
        exported_declaration::<McpDeviceView>(),
        exported_declaration::<McpDeviceStatus>(),
        exported_declaration::<McpGrantView>(),
        exported_declaration::<McpAuthorizationView>(),
        exported_declaration::<McpAuthorizationDecision>(),
        exported_declaration::<WebhookFilterMode>(),
        exported_declaration::<WebhookEvent>(),
        exported_declaration::<WebhookFilterEntry>(),
        exported_declaration::<WebhookInput>(),
        exported_declaration::<WebhookDeliveryState>(),
        exported_declaration::<WebhookView>(),
        exported_declaration::<WebhookList>(),
        exported_declaration::<WebhookSecret>(),
        exported_declaration::<WebhookCreated>(),
        exported_declaration::<WebhookTestResult>(),
    ]
    .join("\n");
    format!(
        "// Generated by ts-rs; do not edit.\n\nexport const MCP_COMPLETE_REQUEST_TIMEOUT_MS = {MCP_COMPLETE_REQUEST_TIMEOUT_MS} as const;\n\n{declarations}\n"
    )
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("packages/generated/src/mcp.ts");
    let expected = contracts();
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            expected,
            "generated contracts are stale; rerun generate-mcp-contracts"
        );
    } else {
        fs::write(path, expected).expect("write generated MCP contracts");
    }
}
