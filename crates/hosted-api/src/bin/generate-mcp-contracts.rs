use peppy_hosted_api::mcp::{
    McpAuthorizationDecision, McpAuthorizationView, McpDeviceState, McpDeviceStatus, McpDeviceView,
    McpGrantView, McpScope,
};
use std::{env, fs, path::Path};
use ts_rs::TS;

fn contracts() -> String {
    let declarations = [
        McpDeviceState::decl(),
        McpScope::decl(),
        McpDeviceView::decl(),
        McpDeviceStatus::decl(),
        McpGrantView::decl(),
        McpAuthorizationView::decl(),
        McpAuthorizationDecision::decl(),
    ]
    .join("\n")
    .replace("type ", "export type ");
    format!("// Generated by ts-rs; do not edit.\n\n{declarations}\n")
}

fn main() {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("packages/generated/src/mcp.ts");
    let expected = contracts();
    if check {
        assert_eq!(
            fs::read_to_string(&path).unwrap_or_default(),
            expected,
            "generated contracts are stale; rerun generate-mcp-contracts"
        );
    } else {
        fs::write(path, expected).expect("write generated MCP contracts");
    }
}
